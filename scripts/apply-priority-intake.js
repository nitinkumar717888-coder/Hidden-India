let content = fs.readFileSync('src/lib/db/destinations-data.ts', 'utf8');

let updateCount = 0;
for (const [slug, images] of Object.entries(PRIORITY_IMAGE_TARGETS)) {
  // Find destination block by slug
  const slugRegex = new RegExp(`("slug":\\s*"${slug}"[\\s\\S]*?"images":\\s*\\[)[\\s\\S]*?(\\]\\s*\\n\\s*\\})`);
  if (slugRegex.test(content)) {
    const formattedImages = JSON.stringify(images, null, 10)
      .slice(1, -1) // remove outer brackets
      .trim();

    content = content.replace(slugRegex, `$1\n${formattedImages}\n        $2`);
    updateCount++;
  } else {
    console.warn(`Could not find images array for slug: ${slug}`);
  }
}

fs.writeFileSync('src/lib/db/destinations-data.ts', content, 'utf8');
console.log(`Successfully updated ${updateCount} priority destinations with Hero and Detail candidates.`);
